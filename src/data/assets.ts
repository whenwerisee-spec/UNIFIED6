// Helper to generate realistic historical price waves
function generateHistory(basePrice: number, points: number, trend: 'up' | 'down' | 'volatile' | 'stable'): number[] {
  const history: number[] = [];
  let currentPrice = basePrice * 0.9; // start a bit lower
  
  let drift = 0;
  if (trend === 'up') drift = 0.005;
  if (trend === 'down') drift = -0.005;
  
  for (let i = 0; i < points; i++) {
    // Add some random noise and wave logic
    const noise = (Math.random() - 0.48) * (basePrice * 0.02);
    const sineWave = Math.sin((i / points) * Math.PI * 4) * (basePrice * 0.03);
    currentPrice = currentPrice + noise + sineWave + (basePrice * drift);
    
    // Ensure price doesn't go below zero
    if (currentPrice <= 0) currentPrice = 0.01;
    history.push(parseFloat(currentPrice.toFixed(2)));
  }
  return history;
}

